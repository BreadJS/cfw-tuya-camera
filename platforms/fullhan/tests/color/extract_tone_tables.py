#!/usr/bin/env python3
"""Reproduce bounded low16 tables used by exact111a88, without a stock loader."""
import hashlib,struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
im=(ROOT.parent/'ipcam_hack_extracted/live_camera/dgiot.bin').read_bytes();p=(ROOT.parent/'ipcam_hack_extracted/rootfs/usr/bin/day_mis2006_mipi_attr.hex').read_bytes()
assert hashlib.sha256(im).hexdigest()=='bdc0fd42a67fc2c51ae6caff380b9d3592953198f6f8faad27e5d1c7aea83714'
assert hashlib.sha256(p).hexdigest()=='467382145b4b7f0211755349d0a3b8f40188c7706777fbe518ef34defb17dbba'
phoff=struct.unpack_from('<I',im,28)[0];sz,n=struct.unpack_from('<HH',im,42)
segments=[struct.unpack_from('<8I',im,phoff+i*sz) for i in range(n)]
def read(address,count):
 for typ,off,va,_,fs,*_ in segments:
  if typ==1 and va<=address and address+count<=va+fs:return im[off+address-va:off+address-va+count]
 raise ValueError(hex(address))
lines=['/* Generated by tests/color/extract_tone_tables.py from SHA-pinned original.',' * Only111a88 low16 curve values and day profile260..2a7 are retained. */','#ifndef CAMERA_TONE_PROFILE_DATA_H','#define CAMERA_TONE_PROFILE_DATA_H','#include <stdint.h>']
lines+=['static const uint8_t camera_tone_profile_bytes[72]={'+','.join(str(v) for v in p[0x260:0x2a8])+'};']
for name,base,stride,start,count,words in [('secondary',0x3d4e6c,0x94,0,1,37),('curve',0x3d5434,0xa4,16,5,41)]:
 lines.append(f'static const uint16_t camera_tone_{name}[{count}][{words}]={{')
 for i in range(count):lines.append('{'+','.join(str(struct.unpack('<I',read(base+(start+i)*stride+4+j*4,4))[0]&65535) for j in range(words))+'},')
 lines.append('};')
lines+=['#endif',''];(ROOT/'src/native/isp/isp_tone_profile_data.h').write_text('\n'.join(lines))
